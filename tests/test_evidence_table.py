"""Guard the frozen evidence table against schema drift and stale numbers.

`outputs/evidence/evidence_table.json` is what the paper quotes from. It is
generated by `scripts/consolidate_evidence.py`, which reads several analysis
JSONs. Two ways it has already gone wrong:

1. It read the pre-fix `counterfactual_follow_3models.json` schema (top-level
   subset keys) and the pre-fix loader, freezing the retracted 0.907/0.931/0.835
   follow numbers into a table labelled "frozen".
2. Its own loader keyed views by `source_pair_id`, repeating the defect that had
   just been fixed upstream.

These tests pin the table to the corrected artifact so neither can recur
silently.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
TABLE = ROOT / "outputs" / "evidence" / "evidence_table.json"
FOLLOW = ROOT / "outputs" / "p0_fun_audio_chat" / "counterfactual_follow_3models.json"
CONFOUND_VIEW = ROOT / "outputs" / "round2" / "confirm_confound_view.json"
STALE = (
    ROOT / "outputs" / "_invalidated"
    / "p0_fun_audio_chat_counterfactual_follow.order-keyed.json"
)


@pytest.fixture(scope="module")
def table():
    if not TABLE.exists():
        pytest.skip("evidence table not generated")
    return json.loads(TABLE.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def follow():
    if not FOLLOW.exists():
        pytest.skip("follow artifact not present")
    return json.loads(FOLLOW.read_text(encoding="utf-8"))


def test_table_matches_the_corrected_follow_artifact(table, follow):
    """Every follow number in the table must equal the corrected artifact.

    Both artifacts key models by identity (``r2_qwen3b``), not by prediction
    filename. They diverged once: the follow artifact keyed on ``path.stem``, so
    the v2 run produced ``r2v2_qwen3b`` and this test had to bridge the two with
    an alias. That is the silent schema drift ``--keys`` now prevents, so the
    lookup below is direct and fails loudly if the keys ever disagree again.
    """

    checked = 0
    for key, model in table["models"].items():
        block = model.get("follow")
        if not block:
            continue
        src = follow["models"][key]["by_aggregation"]["pooled_both_orders"]
        assert block["original_accuracy"] == pytest.approx(src["accuracy_original"])
        assert block["raw_selectivity"] == pytest.approx(
            src["raw_change_rate"]["selectivity"]
        )
        assert block["sham_change_rate"]["P_change_sham"] == pytest.approx(
            src["sham_floor"]["P_change_sham"]
        )
        for name in ("all", "E1_orig_correct", "E2_orig_and_same", "E3_all_three"):
            assert block["subsets"][name]["n"] == src[name]["n"]
            assert block["subsets"][name]["follow_diff"]["rate"] == pytest.approx(
                src[name]["follow_diff"]["rate"]
            )
        pm = follow["models"][key]["pair_mean"]
        for name in ("all", "E2_orig_and_same"):
            assert block["pair_mean"][name]["follow_diff"] == pytest.approx(
                pm[name]["follow_diff"]
            )
        checked += 1
    assert checked >= 3, "expected all three models to carry a follow block"


def test_table_does_not_carry_the_retracted_numbers(table):
    """The quarantined pre-fix numbers must not appear as current values."""

    if not STALE.exists():
        pytest.skip("quarantined artifact not present")
    old = json.loads(STALE.read_text(encoding="utf-8"))
    old_e2 = old["models"]["fun_audio_chat_8b"]["E2_orig_and_same"]["follow_diff"]["rate"]

    block = table["models"]["fun_audio_chat_8b"]["follow"]
    assert block["subsets"]["E2_orig_and_same"]["follow_diff"]["rate"] != pytest.approx(
        old_e2, abs=0.01
    ), "the evidence table is quoting the retracted order-keyed follow number"


def test_table_uses_pooled_two_order_views(table):
    """The follow table must state its aggregation and use n=1200, not n=600."""

    for key, model in table["models"].items():
        block = model.get("follow")
        if not block:
            continue
        assert block["aggregation"] == "pooled_both_orders"
        assert block["n_views"] == 1200
        assert block["n_source_pairs"] == 600


def test_view_level_confound_numbers_are_frozen(table):
    artifact = json.loads(CONFOUND_VIEW.read_text(encoding="utf-8"))
    source_key = "outputs/round2/confirm_confound_view.json"
    digest = hashlib.sha256(CONFOUND_VIEW.read_bytes()).hexdigest()
    assert table["sources_sha256"][source_key] == digest

    frozen = table["confound_matched_view"]
    assert frozen["aggregation"] == artifact["aggregation"]
    for key, source in artifact["models"].items():
        result = frozen["models"][key]
        assert result["matched_items"] == source["matched_items"]
        assert result["matched_trials"] == source["matched_views"]
        assert result["matched_selectivity"] == pytest.approx(source["matched_selectivity"])
        assert result["matched_bootstrap_95"] == source["matched_bootstrap_95"]


def test_evidence_script_keys_by_pair_id():
    """The generator must not reintroduce the source_pair_id keying defect."""

    src = (ROOT / "scripts" / "consolidate_evidence.py").read_text(encoding="utf-8")
    assert 'items[row["pair_id"]]' in src
    assert 'items[row["source_pair_id"]]' not in src
